#!/usr/bin/env python3
"""Import the R5.2 Classic town, meadow and eight monster illustrations."""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from build_art import Emitter
from build_lantern_art import indexed

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/lumen/source"
OUT = ROOT / "firmware/rpg/ui/art"
SPECIES = [
    ("SP_SLIME", 45, 27), ("SP_SHROOM", 44, 44),
    ("SP_WOLF", 52, 42), ("SP_WISP", 36, 45),
    ("SP_SKELETON", 44, 49), ("SP_BAT", 52, 36),
    ("SP_GHOST", 41, 47), ("SP_SLIME_KING", 77, 61),
]


def monster_entries(emitter, source, species_limits, columns, rows, prefix, *, crop_boxes=None, component_seeds=None):
    entries = []
    with Image.open(source) as image:
        if image.mode != "RGBA" or image.width != image.height * 2:
            raise ValueError("Monster atlas must be RGBA in a 2:1 aspect ratio")
        size = image.size
        for i, (species, max_width, max_height) in enumerate(species_limits):
            row, col = divmod(i, columns)
            box = crop_boxes[i] if crop_boxes is not None else (
                round(col * image.width / columns), round(row * image.height / rows),
                round((col + 1) * image.width / columns), round((row + 1) * image.height / rows))
            cell = image.crop(box)
            alpha = np.asarray(cell.getchannel("A")) >= 128
            seed = component_seeds.get(species) if component_seeds is not None else None
            if seed is not None:
                # A neighboring silhouette enters this width but is separated
                # by transparent pixels. Keep only the seeded component.
                mask = Image.fromarray(alpha.astype(np.uint8) * 255).copy()
                point = (seed[0] - box[0], seed[1] - box[1])
                if mask.getpixel(point) != 255:
                    raise ValueError(f"Missing alpha component for {species}")
                ImageDraw.floodfill(mask, point, 128)
                alpha = np.asarray(mask) == 128
                cell.putalpha(Image.fromarray(alpha.astype(np.uint8) * 255))
            ys, xs = np.where(alpha)
            if not xs.size or alpha[0].any() or alpha[-1].any() or alpha[:, 0].any() or alpha[:, -1].any():
                raise ValueError(f"Missing or clipped monster in {species}")
            bbox = (int(xs.min()), int(ys.min()), int(xs.max())+1, int(ys.max())+1)
            cut = cell.crop(bbox)
            cut.thumbnail((max_width, max_height), Image.Resampling.NEAREST)
            rgba = np.array(cut)
            mask = rgba[:, :, 3] >= 128
            rgba[~mask, :3] = 0
            rgb = Image.fromarray(rgba[:, :, :3]).quantize(
                colors=96, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE
            ).convert("RGB")
            pixels = np.dstack((np.asarray(rgb), np.where(mask,255,0).astype(np.uint8)))
            entries.append((species, emitter.sprite(f"{prefix}_{i}", pixels), cut.size, bbox))
    return entries, size


def build():
    e = Emitter()
    with Image.open(SOURCE / "environments.png") as image:
        if image.width != 2 * image.height or image.convert("RGBA").getchannel("A").getextrema() != (255,255):
            raise ValueError("Environment atlas must have two opaque square panels")
        size = image.size
        town, meadow = [e.sprite(name, indexed(image.crop((i*image.height, 0, (i+1)*image.height, image.height)), (466,466)))
                        for i, name in enumerate(("lumen_town", "lumen_meadow"))]
    monsters, atlas_size = monster_entries(e, SOURCE / "monsters.png", SPECIES, 4, 2, "lumen_monster")
    header = ('#pragma once\n#include "sprite.h"\n#include "rpg.h"\n'
              'extern const wf_sprite classic_lumen_town, classic_lumen_meadow;\n'
              'extern const wf_sprite classic_lumen_monsters[SP_COUNT];\n')
    c = ('/* Generated by scripts/build_lumen_art.py. */\n#include "lumen_art.h"\n' + "\n".join(e.body)
         + f"\nconst wf_sprite classic_lumen_town = {town};\nconst wf_sprite classic_lumen_meadow = {meadow};\n"
         + "const wf_sprite classic_lumen_monsters[SP_COUNT] = {\n"
         + "".join(f"    [{species}] = {sprite},\n" for species,sprite,_,_ in monsters) + "};\n")
    manifest = {
        "generator": "OpenAI ImageGen",
        "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(SOURCE.iterdir()) if p.is_file()},
        "environment_source_size": size, "environment_runtime_size": [466,466],
        "monster_source_size": atlas_size,
        "monsters": [{"species": sp, "runtime_size": size, "source_cell_bbox": box} for sp,_,size,box in monsters],
        "conversion": "Nearest-neighbor, indexed RGB565, opaque environment palettes at most 240 colors, monster palettes at most 96 colors and alpha threshold 128",
    }
    return {OUT/"lumen_art.c": c, OUT/"lumen_art.h": header,
            SOURCE.parent/"manifest.json": json.dumps(manifest, indent=2)+"\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    for path, contents in build().items():
        if check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale Lumen art: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents)
    print("Lumen backdrop and eight monster imports verified")


if __name__ == "__main__":
    main()
