# Accent marks, 2 rows, applied above x-height (lowercase) or above caps.
GRAVE = ['#.', '.#']
ACUTE = ['.#', '#.']
ACCENTED = {
    'à': ('a', GRAVE), 'è': ('e', GRAVE), 'é': ('e', ACUTE), 'ì': ('i', GRAVE),
    'ò': ('o', GRAVE), 'ù': ('u', GRAVE), 'À': ('A', GRAVE), 'È': ('E', GRAVE),
    'É': ('E', ACUTE), 'Ì': ('I', GRAVE), 'Ò': ('O', GRAVE), 'Ù': ('U', GRAVE),
}

def glyph_rows(ch):
    """Returns (rows, top) where rows cover lines from `top` (negative = above caps)."""
    if ch in ACCENTED:
        base, mark = ACCENTED[ch]
        rows = [r for r in G[base]]
        width = max(len(r) for r in rows)
        rows = [r.ljust(width, '.') for r in rows]
        mark = [m for m in mark]
        if ch == 'ì':  # dotless i with accent
            rows[0] = rows[0].replace('#', '.')
            mark = ['#.', '.#']
            width = 2
            rows = [r.ljust(2, '.') for r in rows]
        off = (width - len(mark[0])) // 2 + (1 if width >= 4 else 0)
        def overlay(row, m):
            row = list(row.ljust(width, '.'))
            for i, c in enumerate(m):
                if c == '#' and 0 <= off + i < width:
                    row[off + i] = '#'
            return ''.join(row)
        if base.islower():
            rows[0] = overlay('.' * width, mark[0])
            rows[1] = overlay('.' * width, mark[1])
            return rows, 0
        return [overlay('.' * width, mark[0]), overlay('.' * width, mark[1])] + rows, -2
    return G[ch], 0

def charset():
    chars = [chr(c) for c in range(0x20, 0x7f)]
    extra = list(ACCENTED.keys()) + ['\u00b7', '\u00d7', '\u2026', '\u2192', '\u2605', '\u2665']
    return chars + sorted(extra)
