#!/usr/bin/env python3
"""Import the Lantern Crypt and its final two Classic monster illustrations."""
import argparse
import hashlib
import json

from PIL import Image

from build_art import Emitter
from build_lantern_art import indexed
from build_lumen_art import ROOT, OUT, monster_entries

SOURCE = ROOT / "assets/crypt/source"
MONSTERS = [("SP_MIMIC", 62, 47), ("SP_BONE_KING", 66, 62)]


def build():
    emitter = Emitter()
    with Image.open(SOURCE / "environment.png") as image:
        if image.width != image.height or image.convert("RGBA").getchannel("A").getextrema() != (255, 255):
            raise ValueError("Crypt scenery must be one opaque square")
        size = image.size
        scene = emitter.sprite("crypt_floor", indexed(image, (466, 466)))
    monsters, atlas_size = monster_entries(emitter, SOURCE / "monsters.png", MONSTERS, 2, 1, "crypt_monster")
    header = ('#pragma once\n#include "sprite.h"\n'
              'extern const wf_sprite classic_crypt, classic_crypt_mimic, classic_crypt_bone_king;\n')
    source = ('/* Generated by scripts/build_crypt_art.py. */\n#include "crypt_art.h"\n'
              + "\n".join(emitter.body) + "\n"
              + f"const wf_sprite classic_crypt = {scene};\n"
              + f"const wf_sprite classic_crypt_mimic = {monsters[0][1]};\n"
              + f"const wf_sprite classic_crypt_bone_king = {monsters[1][1]};\n")
    manifest = {
        "generator": "OpenAI ImageGen",
        "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(SOURCE.iterdir()) if p.is_file()},
        "environment_source_size": size,
        "environment_runtime_size": [466, 466],
        "monster_source_size": atlas_size,
        "monsters": [{"species": sp, "runtime_size": size, "source_cell_bbox": box}
                     for sp, _, size, box in monsters],
        "conversion": "Nearest-neighbor, indexed RGB565, 240 scenery colors, 96 monster colors and alpha threshold 128",
    }
    return {OUT / "crypt_art.c": source, OUT / "crypt_art.h": header,
            SOURCE.parent / "manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    check = parser.parse_args().check
    for path, contents in build().items():
        if check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale Crypt art: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents)
    print("Lantern Crypt backdrop and two monster imports verified")


if __name__ == "__main__":
    main()
