"""Shared importer for the compact illustrated Classic regions."""
import hashlib
import json

from PIL import Image

from build_art import Emitter
from build_lantern_art import indexed
from build_lumen_art import OUT, monster_entries


def build_region(region, source, scenes, species, *, resolution=233, crops=None, component_seeds=None):
    emitter = Emitter()
    with Image.open(source / "environments.png") as image:
        if image.width != 2 * image.height or image.convert("RGBA").getchannel("A").getextrema() != (255, 255):
            raise ValueError("Region backdrop atlas must be two opaque squares")
        size = image.size
        backdrop_sprites = []
        for i, (name, symbol) in enumerate(scenes):
            square = image.crop((i * image.height + 1, 1, (i + 1) * image.height - 1, image.height - 1))
            data = emitter.sprite(f"{region}_{name}", indexed(square, (resolution, resolution)))
            backdrop_sprites.append((symbol, data))
    monsters, sheet_size = monster_entries(emitter, source / "monsters.png", species, 4, 2,
                                          f"{region}_monster", crop_boxes=crops, component_seeds=component_seeds)
    monster_symbol = f"classic_{region}_monsters"
    scene_names = ", ".join(symbol for symbol, _ in backdrop_sprites)
    header = ('#pragma once\n#include "sprite.h"\n#include "rpg.h"\n'
              f'extern const wf_sprite {scene_names};\n'
              f'extern const wf_sprite {monster_symbol}[SP_COUNT];\n')
    definitions = (f'/* Generated by scripts/build_{region}_art.py. */\n#include "{region}_art.h"\n'
                   + "\n".join(emitter.body) + "\n"
                   + "".join(f"const wf_sprite {symbol} = {data};\n" for symbol, data in backdrop_sprites)
                   + f"const wf_sprite {monster_symbol}[SP_COUNT] = {{\n"
                   + "".join(f"    [{species}] = {sprite},\n" for species, sprite, _, _ in monsters) + "};\n")
    monster_metadata = []
    for i, (species, _, dims, box) in enumerate(monsters):
        entry = {"species": species, "runtime_size": dims}
        if crops is not None:
            entry["source_cell"] = crops[i]
        if component_seeds is not None and species in component_seeds:
            entry["source_component_seed"] = component_seeds[species]
        entry["source_cell_bbox"] = box
        monster_metadata.append(entry)
    manifest = {
        "generator": "OpenAI ImageGen",
        "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(source.iterdir()) if p.is_file()},
        "environment_source_size": size,
        "environment_runtime_size": [resolution, resolution],
        "environment_display_size": [466, 466],
        "monster_source_size": sheet_size,
        "monsters": monster_metadata,
        "conversion": "Nearest-neighbor, indexed RGB565, at most 240 scenery colors, at most 96 monster colors and binary alpha",
    }
    return {OUT / f"{region}_art.c": definitions, OUT / f"{region}_art.h": header,
            source.parent / "manifest.json": json.dumps(manifest, indent=2) + "\n"}
