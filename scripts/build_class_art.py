#!/usr/bin/env python3
"""Import exact-class illustrations without replacing the modular player avatar."""
import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from build_art import Emitter

SOURCE = ROOT / 'assets/classes/source/base-classes.png'
OUTPUT = ROOT / 'firmware/rpg/ui/art'


def sheet(e, path, first):
    source = Image.open(path)
    assert source.mode == 'RGBA' and source.width > source.height
    cells, bounds = [], []
    for row in range(2):
        for col in range(4):
            im = source.crop((round(col*source.width/4), round(row*source.height/2),
                              round((col+1)*source.width/4), round((row+1)*source.height/2)))
            alpha = np.array(im)[:, :, 3] >= 128
            ys, xs = np.where(alpha)
            assert len(xs) and not (alpha[0].any() or alpha[-1].any() or alpha[:, 0].any() or alpha[:, -1].any()), 'clipped class illustration'
            cells.append(im)
            bounds.append((int(xs.min()), int(ys.min()), int(xs.max())+1, int(ys.max())+1))
    foot = max(b[3] for b in bounds)
    top = min(b[1] for b in bounds)
    width = max(max(im.width/2-b[0], b[2]-im.width/2)*2 for im,b in zip(cells,bounds))
    scale = min(76/width, 76/(foot-top))
    sprites = []
    for family, im in enumerate(cells):
        target = Image.new('RGBA', (88,88))
        target.paste(im.resize((round(im.width*scale),round(im.height*scale)), Image.Resampling.NEAREST),
                     (44-round(im.width/2*scale),84-round(foot*scale)))
        rgba = np.array(target)
        mask = rgba[:,:,3] >= 128
        assert mask.any() and not (mask[0].any() or mask[-1].any() or mask[:,0].any() or mask[:,-1].any())
        rgba[~mask,:3] = 0
        rgb = Image.fromarray(rgba[:,:,:3]).quantize(colors=96,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE).convert('RGB')
        sprites.append(e.sprite(f'class_portrait_{first+family}', np.dstack((np.array(rgb),np.where(mask,255,0).astype(np.uint8)))))
    return sprites, dict(source=path.relative_to(ROOT).as_posix(),sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                         class_ids=list(range(first,first+8)),source_cell_bounds=bounds,shared_scale=scale)


def build():
    e=Emitter()
    sprites,base=sheet(e,SOURCE,0)
    advanced,adv=sheet(e,ROOT/'assets/classes/source/advanced-a.png',8)
    sprites+=advanced
    base['source_identity']='exec-ee986e68-ed60-45bf-ae12-58e2a8490899.png'
    adv['source_identity']='exec-5103872b-f962-4f88-bf6e-a6227f49a34e.png'
    adv['rejected_initial_identity']='exec-4a4fe69d-521e-4d59-b554-7f5c83c7901f.png'
    header = '/* Generated by scripts/build_class_art.py. */\n#pragma once\n#include "sprite.h"\n#include "rpg.h"\n#define CLASS_ART_COUNT 16\nextern const wf_sprite class_portraits[CLASS_ART_COUNT];\n'
    source_c = '/* Generated by scripts/build_class_art.py; see assets/classes/README.md. */\n#include "class_art.h"\n'+'\n'.join(e.body)+'\nconst wf_sprite class_portraits[CLASS_ART_COUNT] = {'+','.join(sprites)+'};\n'
    manifest = dict(tool='OpenAI ImageGen',role='Exact-class representative illustrations, separate from the customizable player avatar',
                    count=16,class_ids=list(range(16)),batches=[base,adv],grid=[88,88],display_scale=2,
                    prompt_sha256={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(SOURCE.parent.glob('*.txt'))},
                    transforms=['shared scale within each eight-class batch','foot anchor84','nearest-neighbor','alpha threshold128','96-color palette per illustration','RGB565'],
                    physical_device_tested=False)
    return {OUTPUT/'class_art.h':header,OUTPUT/'class_art.c':source_c,
            ROOT/'assets/classes/manifest.json':json.dumps(manifest,indent=2)+'\n'}


def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
    for path,data in build().items():
        if args.check:
            assert path.exists() and path.read_text()==data, f'stale class art: {path.relative_to(ROOT)}'
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(data)
    print('class art: sixteen exact-class illustrations '+('up to date' if args.check else 'imported'))


if __name__=='__main__':
    main()
