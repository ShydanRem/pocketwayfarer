#!/usr/bin/env python3
"""Import Glass Shore, Sunken Temple and the eight Classic coastal species."""
import argparse
import hashlib
import json

from PIL import Image

from build_art import Emitter
from build_lantern_art import indexed
from build_lumen_art import ROOT, OUT, monster_entries

SOURCE = ROOT / "assets/shore/source"
SPECIES = [
    ("SP_CRAB", 48, 30), ("SP_JELLY", 37, 43),
    ("SP_BLUE_SLIME", 48, 30), ("SP_GOBLIN", 45, 50),
    ("SP_SERPENT", 51, 51), ("SP_DEEP_GHOST", 45, 50),
    ("SP_CRAB_KING", 77, 63), ("SP_LEVIATHAN", 78, 64),
]
# The lower row is offset in the original atlas. Split at the clear gutters.
CROPS = [
    (left, top, right, bottom)
    for cuts, top, bottom in [((0, 443, 887, 1331, 1774), 0, 423),
                             ((0, 440, 839, 1327, 1774), 423, 887)]
    for left, right in zip(cuts, cuts[1:])
]


def build(resolution):
    emitter = Emitter()
    with Image.open(SOURCE / "environments.png") as image:
        if image.width != 2 * image.height or image.convert("RGBA").getchannel("A").getextrema() != (255, 255):
            raise ValueError("Shore backdrop atlas must be two opaque squares")
        size = image.size
        backdrop_sprites = []
        for i, name in enumerate(("shore_field", "shore_temple")):
            square = image.crop((i * image.height + 1, 1, (i + 1) * image.height - 1, image.height - 1))
            backdrop_sprites.append(emitter.sprite(name, indexed(square, (resolution, resolution))))
    shore, temple = backdrop_sprites
    monsters, sheet_size = monster_entries(emitter, SOURCE / "monsters.png", SPECIES, 4, 2,
                                          "shore_monster", crop_boxes=CROPS)
    header = ('#pragma once\n#include "sprite.h"\n#include "rpg.h"\n'
              'extern const wf_sprite classic_shore, classic_temple;\n'
              'extern const wf_sprite classic_shore_monsters[SP_COUNT];\n')
    definitions = ('/* Generated by scripts/build_shore_art.py. */\n#include "shore_art.h"\n'
                   + "\n".join(emitter.body) + "\n"
                   + f"const wf_sprite classic_shore = {shore};\n"
                   + f"const wf_sprite classic_temple = {temple};\n"
                   + "const wf_sprite classic_shore_monsters[SP_COUNT] = {\n"
                   + "".join(f"    [{species}] = {sprite},\n" for species, sprite, _, _ in monsters) + "};\n")
    manifest = {
        "generator": "OpenAI ImageGen",
        "sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(SOURCE.iterdir()) if p.is_file()},
        "environment_source_size": size,
        "environment_runtime_size": [resolution, resolution],
        "environment_display_size": [466, 466],
        "monster_source_size": sheet_size,
        "monsters": [{"species": species, "runtime_size": dims, "source_cell": cell, "source_cell_bbox": box}
                     for (species, _, dims, box), cell in zip(monsters, CROPS)],
        "conversion": "Nearest-neighbor, indexed RGB565, at most 240 scenery colors, at most 96 monster colors and binary alpha",
    }
    return {OUT / "shore_art.c": definitions, OUT / "shore_art.h": header,
            SOURCE.parent / "manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--resolution", type=int, choices=(233, 466), default=233,
                        help="sample 466 for the full-size benchmark")
    args = parser.parse_args()
    for path, contents in build(args.resolution).items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale Shore art: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents)
    print(f"Glass Shore and Sunken Temple at {args.resolution}px, eight coastal monsters verified")


if __name__ == "__main__":
    main()
