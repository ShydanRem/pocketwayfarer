#!/usr/bin/env python3
"""Generates every bitmap used by the firmware from the procedural sources in
scripts/art. Output is deterministic and committed, so building the firmware
never needs Python; run this only after changing the art.

  python3 scripts/build_art.py            # regenerate C sources + previews
  python3 scripts/build_art.py --check    # fail if committed output is stale
"""
import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts' / 'art'))

import font5x7  # noqa: E402
import foes  # noqa: E402
import icons  # noqa: E402
import pets  # noqa: E402
import scenes  # noqa: E402

OUT = ROOT / 'firmware' / 'pet' / 'ui' / 'art'
FONTS = ROOT / 'firmware' / 'common' / 'ui' / 'fonts'
PREVIEW = ROOT / 'docs' / 'img' / 'pet'


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


class Emitter:
    def __init__(self):
        self.body = []
        self.count = 0

    def sprite(self, name, img):
        """img: HxWx4 (RGBA) or HxWx3. Index 0 is transparent."""
        h, w = img.shape[:2]
        alpha = img[:, :, 3] if img.shape[2] == 4 else np.full((h, w), 255, np.uint8)
        colors = {}
        idx = np.zeros((h, w), np.uint8)
        start = 1 if img.shape[2] == 4 else 0
        for y in range(h):
            for x in range(w):
                if alpha[y, x] < 128:
                    continue
                c = rgb565(*[int(v) for v in img[y, x, :3]])
                if c not in colors:
                    colors[c] = len(colors) + start
                idx[y, x] = colors[c]
        assert len(colors) + start <= 256, name
        pal = [0] * start + sorted(colors, key=lambda c: colors[c])
        self.body.append(f'static const uint16_t {name}_pal[{len(pal)}] = {{' +
                         ','.join(f'0x{c:04x}' for c in pal) + '};')
        flat = idx.flatten()
        lines = []
        for i in range(0, len(flat), 40):
            lines.append('    ' + ','.join(str(int(v)) for v in flat[i:i + 40]))
        self.body.append(f'static const uint8_t {name}_px[{len(flat)}] = {{\n' + ',\n'.join(lines) + '\n};')
        self.count += 1
        return f'{{{w}, {h}, {1 if start else 0}, {len(pal)}, {name}_pal, {name}_px}}'


def build_sprites():
    e = Emitter()
    tables = []
    # Companions: [form][expression]; the seed uses frames 0..2 for its cracks.
    rows = []
    for form, painter in enumerate(pets.FORMS):
        cells = []
        for k, expr in enumerate(pets.EXPRESSIONS):
            img = pets.seed(min(k, 2)) if painter is None else painter(expr)
            cells.append(e.sprite(f'pet{form}_{k}', img))
        rows.append('    {' + ', '.join(cells) + '}')
    tables.append(f'const wf_sprite wf_pet_sprites[WF_FORM_COUNT][WF_EXPR_COUNT] = {{\n' + ',\n'.join(rows) + '\n};')
    rows = []
    for n, (name, painter) in enumerate(foes.species_frames()):
        cells = [e.sprite(f'foe{n}_{k}', painter(f)) for k, f in enumerate(foes.FRAMES)]
        rows.append('    {' + ', '.join(cells) + '}')
    tables.append('const wf_sprite wf_foe_sprites[WF_SP_COUNT][2] = {\n' + ',\n'.join(rows) + '\n};')
    cells = [e.sprite(f'item{n}', f().render()) for n, f in enumerate(icons.ITEMS)]
    tables.append('const wf_sprite wf_item_icons[WF_IT_COUNT] = {\n    ' + ',\n    '.join(cells) + '\n};')
    cells = [e.sprite(f'icon_{name}', f().render()) for name, f in icons.UI]
    tables.append('const wf_sprite wf_ui_icons[WF_ICON_COUNT] = {\n    ' + ',\n    '.join(cells) + '\n};')
    sc = scenes.all_scenes()
    cells = [e.sprite(f'scene_{name}', img) for name, img in sc]
    tables.append('const wf_sprite wf_scenes[WF_SCENE_COUNT] = {\n    ' + ',\n    '.join(cells) + '\n};')

    header = ['/* Generated by scripts/build_art.py — do not edit. */', '#pragma once', '#include <stdint.h>',
              '#include "game.h"', '#include "world.h"', '',
              '#include "sprite.h"', '',
              'enum { WF_EXPR_IDLE, WF_EXPR_BLINK, WF_EXPR_HAPPY, WF_EXPR_SAD, WF_EXPR_EAT, WF_EXPR_SLEEP, WF_EXPR_COUNT };',
              'enum {']
    header += [f'    WF_ICON_{name.upper()},' for name, _ in icons.UI]
    header += ['    WF_ICON_COUNT', '};', 'enum {']
    header += [f'    WF_SCENE_{name.upper()},' for name, _ in sc]
    header += ['    WF_SCENE_COUNT', '};', '',
               f'#define WF_SCENE_SIZE {scenes.N}',
               '/* Island centres on the world map, in scene pixels. */',
               'static const uint8_t wf_map_islands[5][2] = {' +
               ', '.join(f'{{{x}, {y}}}' for x, y in scenes.MAP_ISLANDS) + '};', '',
               'extern const wf_sprite wf_pet_sprites[WF_FORM_COUNT][WF_EXPR_COUNT];',
               'extern const wf_sprite wf_foe_sprites[WF_SP_COUNT][2];',
               'extern const wf_sprite wf_item_icons[WF_IT_COUNT];',
               'extern const wf_sprite wf_ui_icons[WF_ICON_COUNT];',
               'extern const wf_sprite wf_scenes[WF_SCENE_COUNT];', '']
    source = ['/* Generated by scripts/build_art.py — do not edit. */', '#include "art.h"', ''] + e.body + [''] + tables + ['']
    return '\n'.join(header), '\n'.join(source), sc


def build_font(scale, name):
    chars = font5x7.charset()
    bits = []
    dsc = ['    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id 0 */']
    for ch in chars:
        rows, top = font5x7.glyph_rows(ch)
        width = max(len(r) for r in rows)
        rows = [r.ljust(width, '.') for r in rows]
        # trim blank rows top/bottom
        nonblank = [i for i, r in enumerate(rows) if '#' in r]
        adv = (width + 1) * scale
        if ch == ' ':
            adv = 4 * scale
        if not nonblank:
            dsc.append(f'    {{.bitmap_index = {len(bits) // 8}, .adv_w = {adv * 16}, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0}}')
            continue
        r0, r1 = nonblank[0], nonblank[-1]
        sub = rows[r0:r1 + 1]
        # Row index relative to the cap top: line y = top + i. Baseline is line 7.
        bottom_line = top + r1 + 1          # one past last row
        ofs_y = (7 - bottom_line) * scale
        while len(bits) % 8:
            bits.append(0)
        start = len(bits) // 8
        for r in sub:
            for _ in range(scale):
                for c in r:
                    bits.extend([1 if c == '#' else 0] * scale)
        dsc.append(f'    {{.bitmap_index = {start}, .adv_w = {adv * 16}, .box_w = {width * scale}, '
                   f'.box_h = {len(sub) * scale}, .ofs_x = 0, .ofs_y = {ofs_y}}}')
    while len(bits) % 8:
        bits.append(0)
    data = [int(''.join(str(b) for b in bits[i:i + 8]), 2) for i in range(0, len(bits), 8)]
    ascii_n = 0x7f - 0x20
    extra = chars[ascii_n:]
    out = [f'/* {name}: original 5x7 pixel font at {scale}x. Generated by scripts/build_art.py. */',
           '#include "lvgl.h"', '',
           f'static const uint8_t {name}_bitmap[] = {{']
    for i in range(0, len(data), 24):
        out.append('    ' + ','.join(f'0x{v:02x}' for v in data[i:i + 24]) + ',')
    out += ['};', '', f'static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{', ',\n'.join(dsc), '};', '']
    base = ord(extra[0])
    out.append(f'static const uint16_t {name}_extra[] = {{' + ','.join(f'0x{ord(c) - base:04x}' for c in extra) + '};')
    out += [f'static const lv_font_fmt_txt_cmap_t {name}_cmaps[] = {{',
            f'    {{.range_start = 32, .range_length = {ascii_n}, .glyph_id_start = 1, .unicode_list = NULL, '
            '.glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},',
            f'    {{.range_start = {base}, .range_length = {ord(extra[-1]) - base + 1}, .glyph_id_start = {ascii_n + 1}, '
            f'.unicode_list = {name}_extra, .glyph_id_ofs_list = NULL, .list_length = {len(extra)}, '
            '.type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY},', '};', '',
            f'static const lv_font_fmt_txt_dsc_t {name}_dsc = {{',
            f'    .glyph_bitmap = {name}_bitmap, .glyph_dsc = {name}_glyphs, .cmaps = {name}_cmaps,',
            '    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 2, .bpp = 1, .kern_classes = 0, .bitmap_format = 0,',
            '};', '',
            f'const lv_font_t {name} = {{',
            '    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,',
            '    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,',
            f'    .line_height = {12 * scale},',
            f'    .base_line = {3 * scale},',
            '    .subpx = LV_FONT_SUBPX_NONE,',
            '    .underline_position = -1, .underline_thickness = 1,',
            '    .fallback = NULL,',
            f'    .dsc = &{name}_dsc,',
            '};', '']
    return '\n'.join(out)


def previews(sc):
    from PIL import Image, ImageDraw
    PREVIEW.mkdir(parents=True, exist_ok=True)
    bg = (28, 30, 52, 255)
    rows = [[pets.seed(0), pets.seed(1), pets.seed(2)]] + \
           [[p(x) for x in ('idle', 'happy', 'eat', 'sleep')] for p in pets.FORMS[1:]]
    sheet = Image.new('RGBA', (4 * 52, len(rows) * 52), bg)
    for j, r in enumerate(rows):
        for i, im in enumerate(r):
            sheet.alpha_composite(Image.fromarray(im, 'RGBA'), (i * 52 + 2, j * 52 + 2))
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(PREVIEW / 'compagni.png')
    t = foes.species_frames()
    sheet = Image.new('RGBA', (5 * 64, 4 * 64), bg)
    for n, (_, f) in enumerate(t):
        im = Image.fromarray(f('idle'), 'RGBA')
        sheet.alpha_composite(im, ((n % 5) * 64 + (64 - im.width) // 2, (n // 5) * 64 + (64 - im.height) // 2))
    sheet.resize((sheet.width * 3, sheet.height * 3), Image.NEAREST).save(PREVIEW / 'creature.png')
    sheet = Image.new('RGB', (5 * 160, 2 * 160), (0, 0, 0))
    for n, (_, img) in enumerate(sc):
        im = Image.fromarray(img, 'RGB')
        mask = Image.new('L', (156, 156), 0)
        ImageDraw.Draw(mask).ellipse((0, 0, 155, 155), fill=255)
        sheet.paste(im, ((n % 5) * 160 + 2, (n // 5) * 160 + 2), mask)
    sheet.resize((sheet.width * 2, sheet.height * 2), Image.NEAREST).save(PREVIEW / 'scenari.png')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--no-preview', action='store_true')
    args = ap.parse_args()
    header, source, sc = build_sprites()
    files = {
        OUT / 'art.h': header,
        OUT / 'art.c': source,
        FONTS / 'font_small.c': build_font(2, 'wf_font_small'),
        FONTS / 'font_big.c': build_font(3, 'wf_font_big'),
        FONTS / 'font_huge.c': build_font(4, 'wf_font_huge'),
    }
    stale = []
    for path, text in files.items():
        old = path.read_text() if path.exists() else None
        if old != text:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text)
    if args.check:
        if stale:
            sys.exit('stale art output: ' + ', '.join(str(p.relative_to(ROOT)) for p in stale))
        print('art: up to date')
        return
    if not args.no_preview:
        previews(sc)
    for path in files:
        print(f'{path.relative_to(ROOT)}: {hashlib.sha256(path.read_bytes()).hexdigest()[:12]}')


if __name__ == '__main__':
    main()
