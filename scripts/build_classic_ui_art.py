#!/usr/bin/env python3
"""Import the Classic archive backdrop into the existing RGB565 sprite pipeline."""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

from build_art import Emitter
from build_lantern_art import indexed

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/classic-ui"
OUTPUT = ROOT / "firmware/rpg/ui/art"


def build():
    source = ASSETS / "source/archive.png"
    with Image.open(source) as image:
        if image.width != image.height or image.convert("RGBA").getchannel("A").getextrema() != (255, 255):
            raise ValueError("Archive backdrop must be square and opaque")
        size = image.size
        emitter = Emitter()
        sprite = emitter.sprite("archive", indexed(image, (466, 466)))
    prompt = ASSETS / "source/archive-prompt.txt"
    manifest = {
        "source": "source/archive.png",
        "generator": "OpenAI ImageGen",
        "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "prompt_sha256": hashlib.sha256(prompt.read_bytes()).hexdigest(),
        "source_size": size,
        "runtime_size": [466, 466],
        "import": "Nearest-neighbor, 240 colors without dithering, indexed RGB565",
    }
    return {
        OUTPUT / "classic_ui_art.h": '#pragma once\n#include "sprite.h"\nextern const wf_sprite classic_archive;\n',
        OUTPUT / "classic_ui_art.c": (
            '/* Generated by scripts/build_classic_ui_art.py. */\n#include "classic_ui_art.h"\n'
            + "\n".join(emitter.body) + f"\nconst wf_sprite classic_archive = {sprite};\n"
        ),
        ASSETS / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, contents in build().items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale Classic archive asset: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents)
    print("Classic archive backdrop verified")


if __name__ == "__main__":
    main()
