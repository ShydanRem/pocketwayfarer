#!/usr/bin/env python3
"""Import the Classic archive and world atlas into the RGB565 sprite pipeline."""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image

from build_art import Emitter
from build_lantern_art import indexed

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/classic-ui"
OUTPUT = ROOT / "firmware/rpg/ui/art"


def load_backdrop(emitter, name, resolution):
    source = ASSETS / "source" / (name + ".png")
    with Image.open(source) as image:
        if image.width != image.height or image.convert("RGBA").getchannel("A").getextrema() != (255, 255):
            raise ValueError(f"Backdrop {name} must be square and opaque")
        size = image.size
        sprite = emitter.sprite(name, indexed(image, (resolution, resolution)))
    prompt = ASSETS / "source" / (name + "-prompt.txt")
    manifest = {
        "source": source.relative_to(ASSETS).as_posix(),
        "generator": "OpenAI ImageGen",
        "sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
        "prompt_sha256": hashlib.sha256(prompt.read_bytes()).hexdigest(),
        "source_size": size,
        "runtime_size": [resolution, resolution],
        "import": "Nearest-neighbor, 240 colors without dithering, indexed RGB565",
    }
    return sprite, manifest


def build():
    emitter = Emitter()
    sprite, manifest = load_backdrop(emitter, "archive", 466)
    world, manifest["world_atlas"] = load_backdrop(emitter, "world", 233)
    return {
        OUTPUT / "classic_ui_art.h": ('#pragma once\n#include "sprite.h"\n'
                                     'extern const wf_sprite classic_archive, classic_world_atlas;\n'),
        OUTPUT / "classic_ui_art.c": (
            '/* Generated by scripts/build_classic_ui_art.py. */\n#include "classic_ui_art.h"\n'
            + "\n".join(emitter.body) + f"\nconst wf_sprite classic_archive = {sprite};\n"
            + f"const wf_sprite classic_world_atlas = {world};\n"
        ),
        ASSETS / "manifest.json": json.dumps(manifest, indent=2) + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, contents in build().items():
        if args.check:
            if not path.exists() or path.read_text() != contents:
                raise SystemExit(f"Stale Classic archive asset: {path.relative_to(ROOT)}")
        else:
            path.write_text(contents)
    print("Classic archive backdrop and world atlas verified")


if __name__ == "__main__":
    main()
